def _foreign_screens(run_id: str, story_id: str | None) -> set[str]:
    """Screens that belong to other stories, as workspace-relative paths."""
    if not story_id:
        return set()
    root = workspace_path(run_id)
    out: set[str] = set()
    for p in story_screens(run_id):
        owners = stories_in(p.read_text(encoding="utf-8", errors="replace"))
