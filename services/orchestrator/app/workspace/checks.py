_TEST_CALL = re.compile(r"""\bclient\.(get|post|put|patch|delete)\(\s*f?(['"])([^'"]+)\2""", re.I)
_BARE_DECORATOR = re.compile(r"""(@router\.(?:get|post|put|patch|delete)\(\s*)(['"])/(\{[^'"]*|)\2""")


def _called_paths(run_id: str) -> list[str]:
    """Every /api path the story screens and the tests request, normalised."""
    root = workspace_path(run_id)
    paths: list[str] = []
    for p in story_screens(run_id):
        code = _COMMENTS.sub(" ", p.read_text(encoding="utf-8", errors="replace"))
        paths += [_normalise(m.group(4)) for m in _API_CALL.finditer(code)]
    tests = root / "tests"
    if tests.is_dir():
        for p in tests.glob("test_*.py"):
            text = p.read_text(encoding="utf-8", errors="replace")
            # Tests request full URLs. Only /api ones are story endpoints: the
            # smoke tests' /health and /openapi.json are not, and counting them
            # made every caller set look ambiguous, so no router was ever moved.
            paths += [_normalise(m.group(3)) for m in _TEST_CALL.finditer(text)
                      if m.group(3).startswith("/api/")]
    return paths


def neutralise_bare_routes(run_id: str, rels: list[str]) -> list[str]:
    """Strip the decorator off any route declared at the root of /api in these files.

    `@router.get("/{incident_id}")` next to proper `/incidents/...` routes once
    turned every other screen's GET into a 422 for two repair rounds, and then
    took the whole deployment down. The function stays (the file still imports);
    only the decorator that mounted it at the root goes. Returns notes.
    """
    root = workspace_path(run_id)
    notes: list[str] = []
    for rel in rels:
        key = rel.replace("\\", "/").lstrip("./")
        path = root / key
        if not (key.startswith("backend/app/routers/") and key.endswith(".py") and path.is_file()):
            continue
        if path.name in (EXAMPLE_ROUTER, GENERIC_ROUTER):
            continue
        src = path.read_text(encoding="utf-8", errors="replace")
        try:
            tree = ast.parse(src)
        except SyntaxError:
            continue
        drop: list[tuple[int, int, str, str]] = []  # (first line, last line, path, function)
        for node in tree.body:
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for deco in node.decorator_list:
                if not (isinstance(deco, ast.Call) and isinstance(deco.func, ast.Attribute)
                        and deco.func.attr.lower() in _HTTP_METHODS_LOWER and deco.args
                        and isinstance(deco.args[0], ast.Constant) and isinstance(deco.args[0].value, str)):
                    continue
                route = deco.args[0].value
                route = route if route.startswith("/") else "/" + route
                prefix = ""
                if _is_bare(f"{ROUTER_PREFIX}{route}"):
                    drop.append((deco.lineno, deco.end_lineno or deco.lineno, route, node.name))
        if not drop:
            continue
        lines = src.splitlines(keepends=True)
        for first, last, _, _ in sorted(drop, reverse=True):
            del lines[first - 1:last]
        new = "".join(lines)
        try:
            ast.parse(new)
        except SyntaxError:
            continue
        path.write_text(new, encoding="utf-8", newline="\n")
        for _, _, route, fn in drop:
            notes.append(f"{key}: removed the route `{route}` from `def {fn}` — declared at the root of /api it is "
                         "served as /api/{…} and swallows every other story's path (every GET answered 422). "
                         "If the story needs it, declare it under the resource: `/incidents/{incident_id}`.")
    return notes


_HTTP_METHODS_LOWER = {"get", "post", "put", "patch", "delete"}


def mount_bare_routers(run_id: str) -> list[str]:
    """Give a story router declared at "/" the resource path its callers already use.

    A local model wrote `@router.get("/")` while its own screen and tests
    requested /api/llm-overviews, and kept the bare path through three repairs
    with the served routes listed back to it each time. Worse, once repairs ran
    out the Tester was told that tests contradicting the verified routes are
    wrong — so it would have "fixed" correct tests to match the broken router.

    When exactly one story router is declared at "/" and its callers agree on
    exactly one path that nothing serves, its decorators are rewritten to that
    path. Tests and the browser check still judge the result; this only removes
    a mismatch every caller already agrees on, and never guesses between two.
    """
    routes = declared_routes(run_id)
    bare = sorted({r["file"] for r in routes
                   if r["file"].startswith("backend/app/routers/") and _is_bare(r["path"])})
    if len(bare) != 1:
        return []
    # The bare router's own routes do not count as serving anything: its
    # "/{item_id}" would otherwise match every path its callers use.
    patterns = [_route_pattern(r["path"]) for r in routes if r["file"] != bare[0]]
    bases = {
        path.split("/")[2]
        for path in _called_paths(run_id)
        if path.count("/") >= 2 and not any(p.match(path) for p in patterns)
    }
    if len(bases) != 1:
        return []
    base = bases.pop()
    if not re.fullmatch(r"[A-Za-z0-9_-]+", base):
        return []
    target = workspace_path(run_id) / bare[0]
    text = target.read_text(encoding="utf-8", errors="replace")
    if re.search(r"APIRouter\([^)]*prefix\s*=", text):
        return []

    def _rewrite(m: re.Match[str]) -> str:
        rest = f"/{m.group(3)}" if m.group(3) else ""
        return f"{m.group(1)}{m.group(2)}/{base}{rest}{m.group(2)}"

    fixed = _BARE_DECORATOR.sub(_rewrite, text)
    if fixed == text:
        return []
    target.write_text(fixed, encoding="utf-8")
    return [f"{bare[0]} declared its routes at '/'; the platform moved them to /api/{base}, "
            "the path its screen and tests call"]


