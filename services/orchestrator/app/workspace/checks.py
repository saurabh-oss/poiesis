"""The platform's checks on a generated frontend, and the screen registry.

pytest exercises the backend only, so for a while nothing ever ran the frontend.
A story went green, was reviewed, deployed and released with a page that threw
"api is not defined" on load and showed only the scaffold placeholder. These
checks run inside the build's repair loop, next to pytest, and their findings go
back to the Developer in the same output — so a broken screen is repaired before
anyone sees it, rather than discovered by the stakeholder after release.

Two layers:

* Static checks here in Python: JSX, dialogs standing in for an interface,
  placeholder comments, calls to API paths the backend does not serve, duplicate
  routes, and a story with no screen at all.
* Node in a throwaway container: every frontend file must parse, and every screen
  module must load without touching the DOM and export { title, render }.

The browser check after deploy (browser_check.py) covers what neither can: the
screens actually rendering against the live API.
"""
