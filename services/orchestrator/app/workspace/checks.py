def _route_functions(src: str) -> dict[tuple[str, str], ast.FunctionDef | ast.AsyncFunctionDef]:
    """(METHOD, declared path) -> the decorated function, for one router module."""
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return {}
    out: dict[tuple[str, str], ast.FunctionDef | ast.AsyncFunctionDef] = {}
    for node in tree.body:
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for deco in node.decorator_list:
            if (isinstance(deco, ast.Call) and isinstance(deco.func, ast.Attribute)
                    and deco.func.attr.lower() in ("get", "post", "put", "patch", "delete") and deco.args
                    and isinstance(deco.args[0], ast.Constant) and isinstance(deco.args[0].value, str)):
                route = deco.args[0].value
                out[(deco.func.attr.upper(), route if route.startswith("/") else "/" + route)] = node
    return out


def _screen_calls(run_id: str, skip: set[str]) -> list[tuple[str, str]]:
    """Every (METHOD or '', normalised path) a screen not in `skip` calls."""
    root = workspace_path(run_id)
    calls: list[tuple[str, str]] = []
    for path in story_screens(run_id):
        rel = path.relative_to(root).as_posix()
        if rel in skip:
            continue
        code = _COMMENTS.sub(" ", path.read_text(encoding="utf-8", errors="replace"))
        for call in _API_CALL.finditer(code):
            calls.append(((call.group(2) or "").upper(), _normalise(call.group(4))))
    return calls


def preserve_routes(run_id: str, files: dict[str, str]) -> tuple[dict[str, str], list[str]]:
    """Put back an endpoint a router rewrite dropped while another screen still calls it.

    A metrics story once returned `routers/metrics.py` complete with its own
    routes and without the dashboard's `/metrics/dashboard`, which an earlier
    story had put in the same file. The dashboard answered 404 on the next
    deploy and the round was lost. Dropped route functions that a screen
    outside this reply still calls are appended back, with their imports.
    """
    root = workspace_path(run_id)
    out = dict(files)
    restored: list[str] = []
    calls = _screen_calls(run_id, {k.replace("\\", "/").lstrip("./") for k in files})
    for rel, new in files.items():
        key = rel.replace("\\", "/").lstrip("./")
        if not (key.startswith("backend/app/routers/") and key.endswith(".py")) or not isinstance(new, str):
            continue
        current = root / key
        if not current.is_file():
            continue
        old = current.read_text(encoding="utf-8", errors="replace")
        if not new.strip():
            # An empty file deletes it. In the enterprise DupeGuard run three stories' repairs
            # deleted routers other stories' screens called (S5 took S4's scan, S8 the known
            # issues S6 and S7 used), and four screens answered 404. A router another screen
            # still calls is kept whole.
            called = [f"{m} {p}" for (m, p) in _route_functions(old)
                      if any(_route_pattern(_normalise(p)).match(c) and (not cm or cm == m) for cm, c in calls)]
            if called:
                out[rel] = old
                restored += [f"{key}: not deleted — other screens call {', '.join(called[:4])}"]
            continue
        old_routes, new_routes = _route_functions(old), _route_functions(new)
        if not old_routes or not new_routes:
            continue
        # A path is "still served" when the new file declares it, whatever the function is called.
        served = {(m, _normalise(p)) for (m, p) in new_routes}
        dropped = {k: fn for k, fn in old_routes.items() if (k[0], _normalise(k[1])) not in served}
        needed = {}
        for (method, path), fn in dropped.items():
            pattern = _route_pattern(_normalise(path))
            if any(pattern.match(called) and (not m or m == method) for m, called in calls):
                needed[(method, path)] = fn
        if not needed:
            continue
        try:
            old_tree, new_tree = ast.parse(old), ast.parse(new)
        except SyntaxError:
            continue
        imports = (ast.Import, ast.ImportFrom)
        have = {ast.get_source_segment(new, n) for n in new_tree.body if isinstance(n, imports)}
        missing = [s for n in old_tree.body if isinstance(n, imports)
                   and (s := ast.get_source_segment(old, n)) and s not in have and "__future__" not in s]
        new_names = {n.name for n in new_tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))}
        segments = []
        old_lines = old.splitlines()
        for (method, path), fn in needed.items():
            # The decorators are not part of the function's own segment; without
            # them the endpoint comes back as a plain function nothing serves.
            start = min([d.lineno for d in fn.decorator_list] + [fn.lineno]) - 1
            seg = "\n".join(old_lines[start:fn.end_lineno or fn.lineno])
            if fn.name in new_names:
                seg = seg.replace(f"def {fn.name}(", f"def {fn.name}_kept(", 1)
            segments.append(seg)
        lines = new.rstrip("\n").splitlines()
        last = max((n.end_lineno or 0 for n in new_tree.body if isinstance(n, imports)), default=0)
        merged = "\n".join(lines[:last] + missing + lines[last:]) + "\n\n\n" + "\n\n\n".join(segments) + "\n"
        try:
            ast.parse(merged)
        except SyntaxError:
            continue
        out[rel] = merged
        restored += [f"{key}: {m} {p} (another screen calls it)" for (m, p) in needed]
    return out, restored


def preserve_shared(run_id: str, files: dict[str, str]) -> tuple[dict[str, str], list[str]]:
    """Put back what a rewrite of a shared file dropped, when something still uses it.

    Stories return schemas.py, models.py and init.sql complete. A model that is
    shown a truncated copy, or simply forgets, drops an earlier story's class and
    breaks that story at import time. Dropped definitions still referenced
    elsewhere are re-appended (with the imports they came with); dropped tables
    are always restored, because a model depends on them.
    """
    root = workspace_path(run_id)
    out = dict(files)
    restored: list[str] = []

    if REQUIREMENTS in out and (root / REQUIREMENTS).is_file():
        baseline = _baseline_requirements()
        if baseline:
            merged, lost = merge_requirements(baseline, str(out[REQUIREMENTS]))
            if lost:
                out[REQUIREMENTS] = merged
                restored += [f"{REQUIREMENTS}: {n}" for n in lost]

    for rel in SHARED_PY:
        new = out.get(rel)
        current = root / rel
        if new is None or not current.is_file():
            continue
        old = current.read_text(encoding="utf-8", errors="replace")
        try:
            old_tree, new_tree = ast.parse(old), ast.parse(new)
        except SyntaxError:
            continue
        defs = (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)
        kept = {n.name for n in new_tree.body if isinstance(n, defs)}
        others = _elsewhere(root, rel, out)
        lost = [n for n in old_tree.body if isinstance(n, defs) and n.name not in kept
                and re.search(rf"\b{re.escape(n.name)}\b", others)]
        if not lost:
            continue
        imports = (ast.Import, ast.ImportFrom)
        have = {ast.get_source_segment(new, n) for n in new_tree.body if isinstance(n, imports)}
        missing = [s for n in old_tree.body if isinstance(n, imports)
                   and (s := ast.get_source_segment(old, n)) and s not in have and "__future__" not in s]
        lines = new.rstrip("\n").splitlines()
        last = max((n.end_lineno or 0 for n in new_tree.body if isinstance(n, imports)), default=0)
        segments = [ast.get_source_segment(old, n) or "" for n in lost]
        merged = "\n".join(lines[:last] + missing + lines[last:]) + "\n\n\n" + "\n\n\n".join(segments) + "\n"
        try:
            ast.parse(merged)
        except SyntaxError:
            continue
        out[rel] = merged
        restored += [f"{rel}: {n.name}" for n in lost]

    new_sql = out.get(SHARED_SQL)
    current_sql = root / SHARED_SQL
    if new_sql is not None and current_sql.is_file():
        old_sql = current_sql.read_text(encoding="utf-8", errors="replace")
        kept_tables = {m.group(1).lower() for m in _TABLE.finditer(new_sql)}
        lost_tables = [m for m in _TABLE.finditer(old_sql) if m.group(1).lower() not in kept_tables]
        if lost_tables:
            new_sql = (new_sql.rstrip() + "\n\n"
                       + "\n\n".join(m.group(0) for m in lost_tables) + "\n")
            restored += [f"{SHARED_SQL}: {m.group(1)}" for m in lost_tables]

        # Restoring the table but not its rows loses the data the application was
        # meant to open with, and nothing goes red: every screen still renders,
        # against an empty database. Only the all-or-nothing case is put back,
        # because a story that rewrote some of a table's rows may mean it.
        was = _inserts_by_table(old_sql)
        now = _inserts_by_table(new_sql)
        # Rows go back against the table as it is *now*. Restoring them as written
        # onto a rewritten table - one that dropped a column the rows still name -
        # produced an init.sql Postgres rejects, so the database would crash-loop
        # and the story could not be repaired: the Developer was told the rows were
        # kept for it, and never shown them to fix.
        tables = _table_columns(new_sql)
        for t in sorted(was):
            if not was[t] or now.get(t):
                continue
            adapted: list[str] = []
            dropped_cols: set[str] = set()
            missing: list[str] = []
            for statement in was[t]:
                fixed, gone, needed = _adapt_insert(statement, tables.get(t, {}))
                if fixed is None:
                    missing = needed
                    break
                adapted.append(fixed)
                dropped_cols |= set(gone)
            if missing:
                restored.append(
                    f"{SHARED_SQL}: NOT restored, reseed it - the rewrite gave {t} required "
                    f"column(s) {', '.join(missing)} that its {_seed_rows(was[t])} seeded "
                    "row(s) never had")
                continue
            new_sql = new_sql.rstrip() + "\n\n" + "\n".join(adapted) + "\n"
            restored.append(
                f"{SHARED_SQL}: {_seed_rows(was[t])} seed row(s) for {t}"
                + (f" (without {', '.join(sorted(dropped_cols))}, which the rewrite removed)"
                   if dropped_cols else ""))
        thinned = [f"{t} ({_seed_rows(now[t])} left of {_seed_rows(was[t])})" for t in sorted(was)
                   if now.get(t) and _seed_rows(now[t]) * 2 < _seed_rows(was[t])]
        if thinned:
            restored.append(f"{SHARED_SQL}: NOT restored, check this - the rewrite thinned the "
                            f"seed data for {', '.join(thinned)}")
        out[SHARED_SQL] = new_sql
    return out, restored
