def backend_issues(run_id: str, own_files: set[str] | None = None) -> list[str]:
    """The handful of Python mistakes the Developer makes over and over.

    Taken from run history rather than imagined. Across fourteen runs the same
    few errors accounted for about half of every story that went red, and each
    one cost a full repair round to rediscover through a traceback:

    * `db = db.get_session()` — a helper shadowing the module it is calling, so
      every request raises UnboundLocalError. The tests pass anyway whenever
      they exercise a different router, and it surfaces only in the browser.
    * `from backend.app import ...` — a path that exists in the repository tree
      but not on the import path, so pytest cannot even collect the module and
      the whole suite reports as one error.
    * a SQLAlchemy model handed to `response_model=`, which fails at import and
      takes the entire application down with it, smoke tests included.

    Each is one AST walk to find here, before pytest runs at all.
    """
    models = set(_model_tables(run_id))
    issues: list[str] = []
    for rel, src in _story_python(run_id, own_files):
        if re.search(r"^\s*(?:from|import)\s+backend[.\s]", src, re.M):
            issues.append(
                f"{rel}: imports `backend...`, a path that does not exist at runtime or under "
                "test — pytest cannot even collect a module that does this, so the whole suite "
                "fails as one error. The package root is `app`: import siblings with two dots "
                "(`from ..db import get_session`, `from ..models import Thing`)."
            )
        try:
            tree = ast.parse(src)
        except SyntaxError as exc:
            issues.append(f"{rel}: does not parse as Python — {exc.msg} at line {exc.lineno}.")
            continue

        for func in [n for n in ast.walk(tree)
                     if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]:
            # `db = db.get_session()` reads a name the same statement makes local,
            # so it raises UnboundLocalError on every call. `query = query.filter(...)`
            # is the same shape and perfectly correct — the difference is only
            # whether the name already holds something at that point, so the check
            # has to walk the function in order and track what is bound.
            bound = {a.arg for a in func.args.args + func.args.kwonlyargs}
            if func.args.vararg:
                bound.add(func.args.vararg.arg)
            if func.args.kwarg:
                bound.add(func.args.kwarg.arg)
            for stmt in ast.walk(func):
                if isinstance(stmt, (ast.Import, ast.ImportFrom)):
                    bound |= {(a.asname or a.name).split(".")[0] for a in stmt.names}
                if isinstance(stmt, ast.Assign) and len(stmt.targets) == 1 and isinstance(stmt.targets[0], ast.Name):
                    name = stmt.targets[0].id
                    value = stmt.value
                    shadows = (isinstance(value, ast.Call) and isinstance(value.func, ast.Attribute)
                               and isinstance(value.func.value, ast.Name)
                               and value.func.value.id == name and name not in bound)
                    if shadows:
                        issues.append(
                            f"{rel}: `{name} = {name}.{value.func.attr}(...)` reads `{name}` in the "
                            f"same statement that makes it local, so `{name}` is unbound when the "
                            "call runs — UnboundLocalError on every request. Take what you need as "
                            "a parameter: `def endpoint(db: Session = Depends(get_session))`, as "
                            "routers/examples.py does."
                        )
                    bound.add(name)
                elif isinstance(stmt, (ast.For, ast.comprehension)):
                    target = getattr(stmt, "target", None)
                    if isinstance(target, ast.Name):
                        bound.add(target.id)
                elif isinstance(stmt, ast.withitem) and isinstance(stmt.optional_vars, ast.Name):
                    bound.add(stmt.optional_vars.id)

        for node in ast.walk(tree):
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
                for kw in node.keywords:
                    if kw.arg != "response_model":
                        continue
                    target = kw.value
                    if (isinstance(target, ast.Subscript) and isinstance(target.slice, ast.Name)):
                        target = target.slice
                    if isinstance(target, ast.Name) and target.id in models:
                        issues.append(
                            f"{rel}: `response_model={target.id}` names a SQLAlchemy model. "
                            "FastAPI raises `Invalid args for response field` at import time, "
                            "which takes the whole application down — every test fails, "
                            "including the scaffold's own. response_model must be a Pydantic "
                            f"schema from schemas.py (e.g. `{target.id}Out`); return the ORM "
                            "object and let it serialise."
                        )

        if re.search(r"\bstrptime\s*\(", src):
            issues.append(
                f"{rel}: calls strptime(). A field typed `datetime.date` in the schema is "
                "already parsed by FastAPI before your function runs, so parsing it again "
                "raises TypeError on a value that is a date, not a string. Type the field and "
                "use it directly."
            )
    issues += enterprise_issues(run_id, own_files)
    return list(dict.fromkeys(issues))


# --- enterprise applications ----------------------------------------------------------

_OUTBOUND = re.compile(r"^\s*(?:import|from)\s+(requests|httpx|smtplib|aiohttp|urllib\.request|urllib3)\b", re.M)


def governed_columns(run_id: str) -> dict[str, tuple[str, str]]:
    """Model class -> (column, workflow) for every Workflow registered in domain/workflows.py."""
    path = workspace_path(run_id) / "backend" / "app" / "domain" / "workflows.py"
    if not path.is_file():
        return {}
    try:
        tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError:
        return {}
    out: dict[str, tuple[str, str]] = {}
    for call in ast.walk(tree):
        if not (isinstance(call, ast.Call) and getattr(call.func, "id", getattr(call.func, "attr", "")) == "Workflow"):
            continue
        args = call.args
        name = args[0].value if args and isinstance(args[0], ast.Constant) else "?"
        model = args[1].id if len(args) > 1 and isinstance(args[1], ast.Name) else None
        field = "status"
        for kw in call.keywords:
            if kw.arg == "model" and isinstance(kw.value, ast.Name):
                model = kw.value.id
            elif kw.arg == "field" and isinstance(kw.value, ast.Constant):
                field = str(kw.value.value)
        if model:
            out[model] = (field, str(name))
    return out


def enterprise_issues(run_id: str, own_files: set[str] | None = None) -> list[str]:
    """What breaks an enterprise application's guarantees, before the code runs.

    The kernel refuses both at runtime too — a governed status written directly is a 409,
    and nothing stops a raw HTTP call from leaving the app unrecorded — but a refusal
    found by the browser costs a repair round; found here it costs nothing.
    """
    root = workspace_path(run_id)
    if not (root / "backend" / "app" / "kernel").is_dir():
        return []
    governed = governed_columns(run_id)
    files = list(_story_python(run_id, own_files))
    services = root / "backend" / "app" / "domain" / "services.py"
    rel_services = "backend/app/domain/services.py"
    if services.is_file() and (own_files is None or rel_services in own_files):
        files.append((rel_services, services.read_text(encoding="utf-8", errors="replace")))
    issues: list[str] = []
    for rel, src in files:
        hit = _OUTBOUND.search(src)
        if hit:
            issues.append(
                f"{rel}: talks to an outside system with `{hit.group(1)}`. In this application every call "
                "out goes through a connector, which records it, retries it and runs in a sandbox without "
                "credentials: `from ..connectors import jira, servicenow, plane, email, slack, teams`.")
        try:
            tree = ast.parse(src)
        except SyntaxError:
            continue
        used = {n.id for n in ast.walk(tree) if isinstance(n, ast.Name)}
        # column -> the workflows governing it, among the models this file uses
        columns: dict[str, list[str]] = {}
        for model, (column, workflow) in governed.items():
            if model in used:
                columns.setdefault(column, []).append(f"{workflow} ({model})")
        if not columns:
            continue
        found = 0
        for node in ast.walk(tree):
            written = None
            if isinstance(node, (ast.Assign, ast.AugAssign, ast.AnnAssign)):
                targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                hit = next((t for t in targets if isinstance(t, ast.Attribute) and t.attr in columns), None)
                if hit is not None and not (isinstance(hit.value, ast.Name) and hit.value.id == "self"):
                    written = (ast.unparse(hit), hit.attr)
            elif isinstance(node, ast.Call) and getattr(node.func, "id", "") == "setattr" and len(node.args) >= 2 \
                    and isinstance(node.args[1], ast.Constant) and node.args[1].value in columns:
                written = (ast.unparse(node), str(node.args[1].value))
            if written is None:
                continue
            issues.append(
                f"{rel}: line {node.lineno} writes `{written[0]}`, a column the "
                f"{' / '.join(columns[written[1]])} workflow governs; the server refuses that write (409, rule "
                f"WF-00). Move the record with `transition(db, row, \"<transition name>\", reason=...)` from "
                f"`..kernel`; an automatic action passes `actor=SYSTEM` (also from `..kernel`) so the role check "
                f"allows it.")
            found += 1
            if found >= 6:
                break
    return issues


