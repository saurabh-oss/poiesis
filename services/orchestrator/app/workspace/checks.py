def _screens_dir(run_id: str) -> Path:
    return workspace_path(run_id).joinpath(*SCREENS_DIR)


def screen_modules(run_id: str) -> list[Path]:
    d = _screens_dir(run_id)
    if not d.is_dir():
        return []
    return sorted(p for p in d.glob("*.js") if p.name != REGISTRY)


def story_screens(run_id: str) -> list[Path]:
    return [p for p in screen_modules(run_id) if p.name != EXAMPLE_SCREEN]


_STORY_TAG = re.compile(r"\bstor(?:y|ies)\s*:\s*([^\n]*)")


def stories_in(text: str) -> list[str]:
    """Story ids a screen declares it delivers: `story: "S1"` or `story: "S1, S3"`."""
    match = _STORY_TAG.search(text)
    return re.findall(r"\bS\d+\b", match.group(1)) if match else []


def regenerate_registry(run_id: str) -> list[str]:
    """Rewrite frontend/screens/index.js to list every story screen.

    ES modules cannot list a directory at runtime, so the registry is generated
    after every build step instead of edited by stories — no story can drop
    another's screen from it, and the worked example disappears once a real
    screen exists.
    """
    d = _screens_dir(run_id)
    if not d.is_dir():
        return []
    real = story_screens(run_id)
    chosen = real or [p for p in screen_modules(run_id) if p.name == EXAMPLE_SCREEN]

    def order(path: Path) -> tuple[int, str]:
        ids = stories_in(path.read_text(encoding="utf-8", errors="replace"))
        return (min((int(i[1:]) for i in ids), default=10**6), path.name)

    chosen.sort(key=order)
    # Each screen is imported on its own and a failure is recorded, not raised:
    # a static `import` graph fails as a whole, and one story's syntax error
    # once left the application with no screens at all.
    lines = ["// Generated by Poiesis after every build step. Do not edit: it is rewritten.",
             "// Screens load one by one, so a broken file cannot take the others down.",
             "const entries = ["]
    lines += [
        f'  {{ id: "{p.stem}", example: {"true" if p.name == EXAMPLE_SCREEN else "false"}, '
        f'load: () => import("./{p.name}") }},'
        for p in chosen
    ]
    lines += ["];", "",
              "export default await Promise.all(entries.map(async (e) => {",
              "  try {",
              "    return { id: e.id, example: e.example, module: (await e.load()).default };",
              "  } catch (err) {",
              "    return { id: e.id, example: e.example, module: null, error: String((err && err.message) || err) };",
              "  }",
              "}));", ""]
    (d / REGISTRY).write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return [p.stem for p in chosen]


