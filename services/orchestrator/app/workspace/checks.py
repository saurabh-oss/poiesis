def criteria_seed_issues(run_id: str, story: dict | None) -> list[str]:
    """A criterion promising "at least N <things>" on first open, against what init.sql seeds.

    A story that delivered 150 generated tickets behind an endpoint someone had to
    call met its own criterion ("when the dashboard loads, then I see at least 150
    tickets") only in theory: a fresh deployment showed the four rows in init.sql.
    Demonstration data is data present when the app is first opened, and the only
    thing that runs then is db/init.sql — so the criterion is checked there.
    """
    if not story:
        return []
    counts = _seed_counts(run_id)
    if not counts:
        return []
    issues: list[str] = []
    for crit in story.get("acceptance_criteria") or []:
        for n, noun in _AT_LEAST.findall(str(crit)):
            need = int(n)
            word = noun.lower().replace("-", "_")
            if need < 5 or word in _NOT_DATA:
                continue
            stems = {word, word.rstrip("s"), word[:-3] + "y" if word.endswith("ies") else word,
                     word[:-2] if word.endswith("es") else word}
            table = next((t for t in counts if t in stems or t.rstrip("s") in stems), None)
            if table is None:
                table = next((t for t in counts if any(s and (s in t or t in s) for s in stems if len(s) > 3)), None)
            if table is None:
                continue
            have = counts.get(table, 0)
            if have < need:
                issues.append(
                    f"db/init.sql: the criterion \"{str(crit)[:110]}\" needs at least {need} {word} present "
                    f"the first time the app is opened, but init.sql seeds only {have} row(s) into "
                    f"`{table}`. The only thing that runs on a fresh deployment is db/init.sql, so "
                    f"demonstration data belongs there as INSERT statements — realistic and varied "
                    f"(distinct names, wording, dates, plans), not generated by an endpoint someone "
                    f"has to call. Write the rows out; a compact tuple per line is fine."
                )
    return list(dict.fromkeys(issues))


async def screen_syntax_errors(run_id: str, rels: list[str]) -> dict[str, str]:
    """`node --check` on each screen; {path: first error line} for the ones that fail.

    A screen shared by two stories was rewritten with an unbalanced `)` and the
    other story could not open its own screen. A file that does not parse is
    caught here, at write time, before it lands on the story that did not write it.
    """
    screens = [r for r in rels if r.startswith("frontend/screens/") and r.endswith(".js")]
    if not screens:
        return {}
    cmd = "; ".join(f"node --check {r} 2>&1 | head -6 | sed 's|^|{r}: |'" for r in screens)
    out = await run_in_sandbox(run_id, cmd, image=NODE_IMAGE, shell="sh", network=False, timeout=120)
    errors: dict[str, str] = {}
    for line in (out.stdout + out.stderr).splitlines():
        for r in screens:
            if line.startswith(r + ": ") and ("SyntaxError" in line or "error" in line.lower()):
                errors.setdefault(r, line[len(r) + 2:].strip()[:200])
    return errors


async def heal_screens(run_id: str) -> list[str]:
    """Restore, from history, every story screen that no longer parses.

    The write-time guard keeps a broken rewrite off disk from now on; this
    covers screens broken before it existed, and any other way a file can end
    up unparseable. Returns a note per screen restored.
    """
    root = workspace_path(run_id)
    rels = [f"frontend/screens/{p.name}" for p in story_screens(run_id)]
    if not rels:
        return []
    broken = await screen_syntax_errors(run_id, rels)
    notes: list[str] = []
    for rel, err in broken.items():
        path = root / rel
        current = path.read_text(encoding="utf-8", errors="replace")
        for sha in history(run_id, rel):
            candidate = show(run_id, sha, rel)
            if not candidate or candidate == current:
                continue
            path.write_text(candidate, encoding="utf-8", newline="\n")
            if not await screen_syntax_errors(run_id, [rel]):
                notes.append(f"{rel} did not parse ({err[:120]}); restored the last version that does, "
                             f"from commit {sha[:10]}")
                break
        else:
            path.write_text(current, encoding="utf-8", newline="\n")
    return notes


async def heal_init_sql(run_id: str) -> str:
    """If db/init.sql does not execute, put back the newest version that does.

    One story's cut-off reply once left init.sql ending inside a row. Its own
    checks caught it, but the file stayed on disk and every later story's checks
    failed on the same line — three stories spent every repair on a file none
    of them had written. Returns a note on what was done, or "".
    """
    root = workspace_path(run_id)
    path = root / SHARED_SQL
    if not path.is_file():
        return ""
    current = await validate_init_sql(run_id)
    if current.ok:
        return ""
    broken = path.read_text(encoding="utf-8", errors="replace")
    for sha in history(run_id, SHARED_SQL):
        candidate = show(run_id, sha, SHARED_SQL)
        if not candidate or candidate == broken:
            continue
        path.write_text(candidate, encoding="utf-8", newline="\n")
        if (await validate_init_sql(run_id)).ok:
            return (f"db/init.sql did not execute ({current.stdout.strip().splitlines()[-1][:160]}); "
                    f"restored the last version that does, from commit {sha[:10]}")
    path.write_text(broken, encoding="utf-8", newline="\n")
    return ""


async def platform_checks(
    run_id: str, story_id: str | None, require_screen: bool, own_files: set[str] | None = None,
    story: dict | None = None,
) -> ExecResult:
    """Static, Node and database checks, as one ExecResult the repair loop can read."""
    root = workspace_path(run_id)
    issues: list[str] = []
    issues += criteria_seed_issues(run_id, story)

    sql = await validate_init_sql(run_id)
    if not sql.ok:
        issues.append(
            "db/init.sql failed when actually executed against Postgres — pytest never "
            "catches this, because it builds its test tables from the Python models instead "
            f"of running init.sql:\n{sql.stdout}"
        )
    else:
        # Only meaningful once init.sql is known to at least run: a column missing
        # from a table that itself failed to create would just be noise on top.
        issues += schema_drift_issues(run_id)

    issues += backend_issues(run_id, own_files)

    if not (root / "frontend").is_dir():
        body = "\n\n".join(f"- {i}" for i in issues)
        return ExecResult(0 if not issues else 1, (HEADER + body) if issues else "", "", False)

    issues += static_issues(run_id, story_id, require_screen, own_files)
    tools = root / ".poiesis"
    tools.mkdir(exist_ok=True)
    (tools / "check_frontend.mjs").write_text(NODE_SCRIPT, encoding="utf-8", newline="\n")
    node = await run_in_sandbox(
        run_id, NODE_COMMAND, image=NODE_IMAGE, shell="sh", network=False, timeout=180
    )
    node_out = (node.stdout + "\n" + node.stderr).strip()
    if not node.ok:
        blocks = [b.strip() for b in node_out.split("\n\n") if b.strip()]
        foreign = _foreign_screens(run_id, story_id)
        mine = [b for b in blocks if b.split(":", 1)[0].strip() not in foreign]
        if mine:
            issues += mine
        elif not blocks:
            issues.append("The frontend check could not run.")
        else:
            node_out = "frontend ok for this story (other stories' screens have their own checks)"

    body = "\n\n".join(f"- {i}" for i in issues) if issues else node_out
    return ExecResult(0 if not issues else 1, HEADER + body, "", False)


