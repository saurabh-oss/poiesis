async def api_smoke(run_id: str, timeout: int = 600) -> tuple[list[dict], str]:
    """GET every route against a seeded in-memory database. Returns (failures, error).

    A workload endpoint once answered 500 to the first real request because of a
    SQLAlchemy call that does not exist; no test had called it, and the browser
    found it after deploy. This finds it before, in the sandbox.
    """
    root = workspace_path(run_id)
    tools = root / ".poiesis"
    tools.mkdir(exist_ok=True)
    (tools / "api_smoke.py").write_text(SMOKE_SCRIPT, encoding="utf-8", newline="\n")
    pg = await _smoke_postgres(run_id)
    try:
        if pg:
            result = await run_in_sandbox(run_id, SMOKE_COMMAND, timeout=timeout, network_name=pg,
                                          env={"SMOKE_DATABASE_URL": "postgresql+psycopg://postgres:poiesis@smoke-db:5432/poiesis"})
        else:
            result = await run_in_sandbox(run_id, SMOKE_COMMAND, timeout=timeout, network=True)
    finally:
        if pg:
            await _proc("docker", "rm", "-f", f"{pg}-db", timeout=30)
            await _proc("docker", "network", "rm", pg, timeout=30)
    marker = "POIESIS_SMOKE_JSON\n"
    if marker not in result.stdout:
        err = (result.stderr or result.stdout).strip()
        lines = [l for l in err.splitlines() if l.strip() and "site-packages" not in l][-16:]
        text = "the API could not be started for the smoke check:\n" + "\n".join(lines)
        # An import error names the story file: that is a failure of that file, not of the check.
        hit = re.search(r"/work/(backend/app/routers/[A-Za-z0-9_]+\.py)", "\n".join(lines))
        if hit and hit.group(1).split("/")[-1] not in (EXAMPLE_ROUTER, GENERIC_ROUTER):
            return [{"path": "(import)", "status": 500, "detail": text, "file": hit.group(1)}], ""
        return [], text
    try:
        rows = json.loads(result.stdout.split(marker, 1)[1])
    except json.JSONDecodeError:
        return [], "the smoke check produced unreadable output"
    # A GET with no parameters that answers 4xx is wrong too: a 422 on /api/metrics is
    # how a stray root route in another router shows itself. But a 422 that only says
    # required query parameters are missing is an endpoint that needs input (a
    # deflection check wants the draft's subject); called bare, that is its answer.
    return [r for r in rows if int(r.get("status", 0)) >= (500 if r.get("parametrised") else 400)
            and not _needs_query(r)], ""


def _needs_query(row: dict) -> bool:
    """A 422 whose every complaint is a missing query parameter."""
    if int(row.get("status", 0)) != 422:
        return False
    try:
        errors = json.loads(row.get("detail") or "").get("detail") or []
    except (ValueError, AttributeError):
        return False
    return bool(errors) and all(isinstance(e, dict) and e.get("type") == "missing"
                                and (e.get("loc") or [None])[0] == "query" for e in errors)


async def _smoke_postgres(run_id: str) -> str | None:
    """A throwaway Postgres on its own network, loaded from db/init.sql. Returns the network name.

    The smoke used to run on SQLite, and an endpoint using SQLite's julianday()
    passed it, then answered 500 on the deployed Postgres. None when Docker
    cannot provide it; the smoke then falls back to SQLite.
    """
    init = workspace_path(run_id) / "db" / "init.sql"
    if not init.is_file():
        return None
    net = f"poiesis-smoke-{run_id}"
    await _proc("docker", "rm", "-f", f"{net}-db", timeout=30)
    await _proc("docker", "network", "rm", net, timeout=30)
    code, _ = await _proc("docker", "network", "create", net, timeout=30)
    if code != 0:
        return None
    code, _ = await _proc(
        "docker", "run", "-d", "--name", f"{net}-db", "--network", net, "--network-alias", "smoke-db",
        "-e", "POSTGRES_PASSWORD=poiesis", "-e", "POSTGRES_DB=poiesis",
        "-v", f"{mount_source(run_id)}/db/init.sql:/docker-entrypoint-initdb.d/init.sql:ro",
        SQL_IMAGE, timeout=60)
    if code != 0:
        await _proc("docker", "network", "rm", net, timeout=30)
        return None
    for _ in range(120):
        code, _ = await _proc("docker", "exec", f"{net}-db", "pg_isready", "-h", "127.0.0.1", "-U", "postgres", timeout=10)
        if code == 0:
            return net
        await asyncio.sleep(0.5)
    await _proc("docker", "rm", "-f", f"{net}-db", timeout=30)
    await _proc("docker", "network", "rm", net, timeout=30)
    return None


def smoke_failures_by_file(run_id: str, failures: list[dict]) -> dict[str, list[dict]]:
    """Which router file serves each failing path."""
    # A story router that declares the same path as the generic data API is the
    # one FastAPI serves, so it is the one a failure belongs to: story routes first.
    declared = sorted(declared_routes(run_id), key=lambda r: r.get("generic") is not None)
    routes = [(r["method"], _route_pattern(r["path"]), r["file"]) for r in declared]
    out: dict[str, list[dict]] = {}
    for f in failures:
        if f.get("file"):
            out.setdefault(f["file"], []).append(f)
            continue
        path = _normalise(str(f.get("path", "")))
        owner = next((file for m, p, file in routes if m == "GET" and p.match(path)), "")
        out.setdefault(owner, []).append(f)
    return out


