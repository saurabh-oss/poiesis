HEADER = "\n\n=== PLATFORM CHECKS: the frontend (implementation problems for the Developer, not test problems) ===\n"


async def _proc(*cmd: str, timeout: int = 60) -> tuple[int, str]:
    proc = await asyncio.create_subprocess_exec(
        *cmd, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.STDOUT,
    )
    try:
        out, _ = await asyncio.wait_for(proc.communicate(), timeout=timeout)
    except asyncio.TimeoutError:
        proc.kill()
        return -1, f"timed out after {timeout}s"
    return (proc.returncode if proc.returncode is not None else -1), out.decode(errors="replace")


async def validate_init_sql(run_id: str) -> ExecResult:
    """Actually run db/init.sql against a throwaway Postgres. Nothing else does.

    pytest builds its tables from the SQLAlchemy models via `Base.metadata.
    create_all` — never from init.sql — so a syntactically broken init.sql
    (most often a reply truncated mid-statement) passes every test cleanly and
    is discovered only when the real database container crash-loops at deploy
    time, taking the whole application down. Running it here, in the repair
    loop, catches exactly what deploy would hit, attributed to the story that
    is being built right now instead of an unattributed "the app didn't start"
    finding that forces the entire sprint to be rebuilt to fix one file.
    """
    root = workspace_path(run_id)
    init = root / "db" / "init.sql"
    if not init.is_file():
        return ExecResult(0, "", "", False)

    name = f"poiesis-sqlcheck-{run_id}"
    await _proc("docker", "rm", "-f", name, timeout=20)
    mount = f"{mount_source(run_id)}/db/init.sql"
    started = False
    try:
        code, out = await _proc(
            "docker", "run", "-d", "--name", name,
            "-e", "POSTGRES_PASSWORD=poiesis", "-e", "POSTGRES_DB=poiesis",
            "-v", f"{mount}:/tmp/init.sql:ro",
            SQL_IMAGE, timeout=30,
        )
        if code != 0:
            return ExecResult(0, "", "", False)  # docker itself unavailable; not this check's job
        started = True
        for _ in range(30):
            code, _ = await _proc("docker", "exec", name, "pg_isready", "-U", "postgres", timeout=10)
            if code == 0:
                break
            await asyncio.sleep(0.5)
        else:
            return ExecResult(0, "", "", False)  # never came up; a real deploy will surface why

        code, out = await _proc(
            "docker", "exec", name, "psql", "-U", "postgres", "-d", "poiesis",
            "-v", "ON_ERROR_STOP=1", "-f", "/tmp/init.sql", timeout=30,
        )
    finally:
        if started:
            await _proc("docker", "rm", "-f", name, timeout=20)

    if code == 0:
        return ExecResult(0, "", "", False)
    lines = [l for l in out.splitlines() if l.strip()]
    return ExecResult(1, "\n".join(lines[-15:]), "", False)


async def platform_checks(
    run_id: str, story_id: str | None, require_screen: bool, own_files: set[str] | None = None,
) -> ExecResult:
    """Static, Node and database checks, as one ExecResult the repair loop can read."""
    root = workspace_path(run_id)
    issues: list[str] = []

    sql = await validate_init_sql(run_id)
    if not sql.ok:
        issues.append(
            "db/init.sql failed when actually executed against Postgres — pytest never "
            "catches this, because it builds its test tables from the Python models instead "
            f"of running init.sql:\n{sql.stdout}"
        )
    else:
        # Only meaningful once init.sql is known to at least run: a column missing
        # from a table that itself failed to create would just be noise on top.
        issues += schema_drift_issues(run_id)

    issues += backend_issues(run_id, own_files)

    if not (root / "frontend").is_dir():
        body = "\n\n".join(f"- {i}" for i in issues)
        return ExecResult(0 if not issues else 1, (HEADER + body) if issues else "", "", False)

    issues += static_issues(run_id, story_id, require_screen, own_files)
    tools = root / ".poiesis"
    tools.mkdir(exist_ok=True)
    (tools / "check_frontend.mjs").write_text(NODE_SCRIPT, encoding="utf-8", newline="\n")
    node = await run_in_sandbox(
        run_id, NODE_COMMAND, image=NODE_IMAGE, shell="sh", network=False, timeout=180
    )
    node_out = (node.stdout + "\n" + node.stderr).strip()
    if not node.ok:
        blocks = [b.strip() for b in node_out.split("\n\n") if b.strip()]
        foreign = _foreign_screens(run_id, story_id)
        mine = [b for b in blocks if b.split(":", 1)[0].strip() not in foreign]
        if mine:
            issues += mine
        elif not blocks:
            issues.append("The frontend check could not run.")
        else:
            node_out = "frontend ok for this story (other stories' screens have their own checks)"

    body = "\n\n".join(f"- {i}" for i in issues) if issues else node_out
    return ExecResult(0 if not issues else 1, HEADER + body, "", False)


# --- keeping shared files whole ---------------------------------------------------------

SHARED_PY = ("backend/app/models.py", "backend/app/schemas.py")
SHARED_SQL = "db/init.sql"
_TABLE = re.compile(r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z_]\w*)\s*\([\s\S]*?\)\s*;", re.I)


def _elsewhere(root: Path, skip: str, proposed: dict[str, str]) -> str:
    """Everything in the backend and tests except one file, including proposed edits."""
    texts: list[str] = []
    for base in ("backend", "tests"):
        for p in (root / base).rglob("*.py"):
            rel = p.relative_to(root).as_posix()
            if rel != skip and rel not in proposed:
                texts.append(p.read_text(encoding="utf-8", errors="replace"))
    texts += [body for rel, body in proposed.items() if rel != skip]
    return "\n".join(texts)


def preserve_shared(run_id: str, files: dict[str, str]) -> tuple[dict[str, str], list[str]]:
    """Put back what a rewrite of a shared file dropped, when something still uses it.

    Stories return schemas.py, models.py and init.sql complete. A model that is
    shown a truncated copy, or simply forgets, drops an earlier story's class and
    breaks that story at import time. Dropped definitions still referenced
    elsewhere are re-appended (with the imports they came with); dropped tables
    are always restored, because a model depends on them.
    """
    root = workspace_path(run_id)
    out = dict(files)
    restored: list[str] = []

    for rel in SHARED_PY:
        new = out.get(rel)
        current = root / rel
        if new is None or not current.is_file():
            continue
        old = current.read_text(encoding="utf-8", errors="replace")
        try:
            old_tree, new_tree = ast.parse(old), ast.parse(new)
        except SyntaxError:
            continue
        defs = (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)
        kept = {n.name for n in new_tree.body if isinstance(n, defs)}
        others = _elsewhere(root, rel, out)
        lost = [n for n in old_tree.body if isinstance(n, defs) and n.name not in kept
                and re.search(rf"\b{re.escape(n.name)}\b", others)]
        if not lost:
            continue
        imports = (ast.Import, ast.ImportFrom)
        have = {ast.get_source_segment(new, n) for n in new_tree.body if isinstance(n, imports)}
        missing = [s for n in old_tree.body if isinstance(n, imports)
                   and (s := ast.get_source_segment(old, n)) and s not in have and "__future__" not in s]
        lines = new.rstrip("\n").splitlines()
        last = max((n.end_lineno or 0 for n in new_tree.body if isinstance(n, imports)), default=0)
        segments = [ast.get_source_segment(old, n) or "" for n in lost]
        merged = "\n".join(lines[:last] + missing + lines[last:]) + "\n\n\n" + "\n\n\n".join(segments) + "\n"
        try:
            ast.parse(merged)
        except SyntaxError:
            continue
        out[rel] = merged
        restored += [f"{rel}: {n.name}" for n in lost]

    new_sql = out.get(SHARED_SQL)
    current_sql = root / SHARED_SQL
    if new_sql is not None and current_sql.is_file():
        old_sql = current_sql.read_text(encoding="utf-8", errors="replace")
        kept_tables = {m.group(1).lower() for m in _TABLE.finditer(new_sql)}
        lost_tables = [m for m in _TABLE.finditer(old_sql) if m.group(1).lower() not in kept_tables]
        if lost_tables:
            out[SHARED_SQL] = (new_sql.rstrip() + "\n\n"
                               + "\n\n".join(m.group(0) for m in lost_tables) + "\n")
            restored += [f"{SHARED_SQL}: {m.group(1)}" for m in lost_tables]
    return out, restored
