def _import_issues(root: Path, rel: str, src: str) -> list[str]:
    """Names a test imports from `app.*` that the workspace does not define.

    `from app.db import SessionLocal` inside a test function fails only when
    that test runs, so it slipped past the module-level checks and cost a story
    five Developer repairs against a file the Developer may not edit. Every
    ImportFrom in the file is checked, wherever it sits, against the module's
    real public names.
    """
    from .interface import _public_names
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return []
    owner: dict[int, str] = {}
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith("test_"):
            for line in range(node.lineno, (node.end_lineno or node.lineno) + 1):
                owner[line] = node.name
    package = root / "backend" / "app"
    issues: list[str] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.ImportFrom) or not node.module:
            continue
        parts = node.module.split(".")
        if parts[0] != "app" or len(parts) < 2:
            continue
        module = package.joinpath(*parts[1:]).with_suffix(".py")
        where = f"{rel}::{owner[node.lineno]}" if node.lineno in owner else rel
        if not module.is_file():
            pkg_init = package.joinpath(*parts[1:]) / "__init__.py"
            if pkg_init.is_file():
                continue
            issues.append(f"{where} imports from `{node.module}`, a module that does not exist in "
                          "backend/app. Import only what VERIFIED IMPORTS lists.")
            continue
        names = _public_names(module.read_text(encoding="utf-8", errors="replace"))
        missing = [a.name for a in node.names if a.name != "*" and a.name not in names]
        if missing:
            issues.append(
                f"{where} imports `{', '.join(missing)}` from `{node.module}`, which does not "
                f"define it — the test fails with ImportError however correct the implementation "
                f"is, and the Developer may not change that file. `{node.module}` defines: "
                f"{', '.join(names[:12]) or 'nothing public'}. Use those (the `client` and "
                "`db_session` fixtures already give you a session), or drop the import."
            )
    return issues


_CLIENT_ATTR = re.compile(r"\bclient\.(?!(?:get|post|put|patch|delete|head|options|request|"
                          r"headers|base_url|cookies|app|close|stream|websocket_connect)\b)(\w+)")
_TEST_FN = re.compile(r"^\s*(?:async\s+)?def\s+(test_\w+)", re.M)
_OWN_SESSION = re.compile(r"\b(Session\s*\(|sessionmaker\s*\(|create_engine\s*\(|SessionLocal\s*\(|TestClient\s*\()")
_ENGINE_IMPORT = re.compile(r"^\s*from\s+app\.db\s+import\s+[^\n]*\bengine\b", re.M)
_OWN_FIXTURE = re.compile(r"^\s*def\s+(client|db_session)\s*\(", re.M)


def required_columns(run_id: str) -> dict[str, set[str]]:
    """{model class: columns a constructor must be given} from backend/app/models.py.

    A column is required when it is mapped without nullable=True, without a
    default or server_default, is not the primary key, and is not annotated as
    optional (`Mapped[str | None]`). Relationships are not columns.
    """
    path = workspace_path(run_id) / "backend" / "app" / "models.py"
    if not path.is_file():
        return {}
    try:
        tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError:
        return {}
    out: dict[str, set[str]] = {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        required: set[str] = set()
        for stmt in node.body:
            if not isinstance(stmt, ast.AnnAssign) or not isinstance(stmt.target, ast.Name):
                continue
            call = stmt.value
            if not isinstance(call, ast.Call) or getattr(call.func, "id", getattr(call.func, "attr", "")) != "mapped_column":
                continue
            ann = ast.unparse(stmt.annotation)
            if "None" in ann or "Optional" in ann:
                continue
            kws = {k.arg: k.value for k in call.keywords}
            if "default" in kws or "server_default" in kws or "default_factory" in kws:
                continue
            if isinstance(kws.get("primary_key"), ast.Constant) and kws["primary_key"].value:
                continue
            if isinstance(kws.get("nullable"), ast.Constant) and kws["nullable"].value:
                continue
            if isinstance(kws.get("autoincrement"), ast.Constant) and kws["autoincrement"].value:
                continue
            required.add(stmt.target.id)
        if required:
            out[node.name] = required
    return out


def _model_seed_issues(run_id: str, rel: str, src: str) -> list[str]:
    """Tests that build a model row without every column the table requires.

    `Ticket(title=..., status=...)` with no `product_area` raises IntegrityError
    inside the test's own seeding, and no implementation can change that.
    """
    required = required_columns(run_id)
    if not required:
        return []
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return []
    owner: dict[int, str] = {}
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith("test_"):
            for line in range(node.lineno, (node.end_lineno or node.lineno) + 1):
                owner[line] = node.name
    issues: list[str] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        name = getattr(node.func, "id", getattr(node.func, "attr", ""))
        if name not in required:
            continue
        if any(isinstance(a, ast.Starred) for a in node.args) or any(k.arg is None for k in node.keywords):
            continue  # **kwargs: cannot tell
        given = {k.arg for k in node.keywords}
        missing = sorted(required[name] - given)
        if missing:
            where = f"{rel}::{owner[node.lineno]}" if node.lineno in owner else rel
            issues.append(
                f"{where} builds `{name}(...)` without `{', '.join(missing)}`, which the table requires "
                f"(NOT NULL, no default). The insert fails with IntegrityError inside the test's own "
                f"seeding, whatever the implementation does. Give every required column a value."
            )
    return list(dict.fromkeys(issues))


def _fixture_issues(rel: str, src: str) -> list[str]:
    """Tests that reach for something the fixtures do not provide.

    `client.session.add(agent)` was invented in three tests at once: the
    TestClient has no session, the `db_session` fixture is the session, and the
    Developer could do nothing about it for six repairs.
    """
    issues: list[str] = []
    if _OWN_FIXTURE.search(src):
        issues.append(
            f"{rel} redefines the `client` or `db_session` fixture. Those come from tests/conftest.py "
            "and point at the test database; a local copy points at nothing that exists while tests "
            "run. Delete the definition and take the fixture as a test argument."
        )
    for block in re.split(r"^(?=\s*(?:async\s+)?def\s+test_)", src, flags=re.M):
        name = _TEST_FN.search(block)
        if not name:
            continue
        if _OWN_SESSION.search(block) or _ENGINE_IMPORT.search(block):
            issues.append(
                f"{rel}::{name.group(1)} builds its own database session or client (Session(...), "
                "sessionmaker, create_engine, TestClient, or `engine` imported from app.db). That "
                "targets the production database, which does not exist while tests run — and "
                "app.db.engine is a function, so `Session(engine)` fails with "
                "\"'_lru_cache_wrapper' object has no attribute 'connect'\". Take the `client` and "
                "`db_session` fixtures as test arguments instead; they are already wired to a real, "
                "empty test database."
            )
        for attr in sorted({m.group(1) for m in _CLIENT_ATTR.finditer(block)}):
            issues.append(
                f"{rel}::{name.group(1)} uses `client.{attr}`, which the TestClient does not have — "
                "it fails with AttributeError whatever the implementation does. `client` only "
                "makes requests; to seed rows take the `db_session` fixture as a second test "
                "argument (`def test_x(client, db_session):`) and use `db_session.add(...)` then "
                "`db_session.commit()`."
            )
    return issues


def _resource_table(path: str, tables: set[str]) -> str | None:
    """`/api/agents/3` -> `agent` when that table is seeded, else None."""
    parts = [p for p in _normalise(path).split("/") if p and p != "api" and not p.startswith("{")]
    for seg in parts[:2]:
        word = seg.lower().replace("-", "_")
        stems = {word, word.rstrip("s"), word[:-3] + "y" if word.endswith("ies") else word,
                 word[:-2] if word.endswith("es") else word}
        for t in tables:
            if t in stems or t.rstrip("s") in stems:
                return t
    return None


def test_issues(run_id: str, test_paths: list[str], own_files: set[str] | None = None) -> list[str]:
    """Tests that cannot pass however correct the implementation is.

    The Tester writes its suite once, before a line of it has ever run, and the
    Developer is forbidden to edit tests — rightly, since that is what stops a
    model writing tests that pass. The cost of that rule is that an impossible
    test is unfixable by anyone until the Tester is asked again, which used to
    happen only after three Developer repairs had already been spent on code
    that was never wrong. These are the shapes that actually showed up:
    `assert 405 == 422` (a POST to a path serving only GET), `assert 0 > 0`
    (rows expected from a database nothing seeded), and a button's label
    asserted inside a JSON body. Catching them here costs one Tester revision
    instead of a whole story.
    """
    root = workspace_path(run_id)
    routes = declared_routes(run_id)
    served = ", ".join(sorted({f"{r['method']} {r['path']}" for r in routes})) or "none"
    by_path: dict[str, set[str]] = {}
    status_for: dict[tuple[str, str], int] = {}
    owner_for: dict[tuple[str, str], str] = {}
    for r in routes:
        key = r["path"].rstrip("/") or "/"
        by_path.setdefault(key, set()).add(r["method"])
        status_for[(r["method"], key)] = r["status"]
        owner_for[(r["method"], key)] = r.get("file", "")

    seeded = {t for t, n in _seed_counts(run_id).items() if n}
    issues: list[str] = []
    for rel in test_paths:
        target = root / rel
        if not target.is_file():
            continue
        src = target.read_text(encoding="utf-8", errors="replace")
        issues.extend(_import_issues(root, rel, src))
        issues.extend(_fixture_issues(rel, src))
        issues.extend(_model_seed_issues(run_id, rel, src))
        for block in re.split(r"^(?=\s*(?:async\s+)?def\s+test_)", src, flags=re.M):
            name_match = re.search(r"def\s+(test_\w+)", block)
            if not name_match:
                continue
            name = name_match.group(1)
            for call in _CLIENT_CALL.finditer(block):
                method, path = call.group(1).upper(), _normalise(call.group(3))
                path = path.rstrip("/") or "/"
                matches = [p for p in by_path if _route_pattern(p).match(path)]
                if not matches:
                    issues.append(
                        f"{rel}::{name} requests {method} {path}, which the API does not serve. "
                        f"Served routes: {served}. Test what exists, or leave the criterion in "
                        "criteria_not_covered."
                    )
                    continue
                allowed = set().union(*(by_path[p] for p in matches))
                if own_files and method in ("POST", "PUT", "PATCH", "DELETE"):
                    owners = {owner_for.get((method, p), "") for p in matches}
                    if owners and not (owners & own_files) and all(owners):
                        issues.append(
                            f"{rel}::{name} creates or changes data through {method} {path}, which "
                            f"belongs to another story ({', '.join(sorted(owners))}). That endpoint may "
                            "not exist or work yet, and its failure lands on this story. Seed rows with "
                            "the `db_session` fixture, or through this story's own routes."
                        )
                if method not in allowed:
                    issues.append(
                        f"{rel}::{name} sends {method} {path}, but that path serves only "
                        f"{', '.join(sorted(allowed))} — FastAPI answers 405 and no "
                        "implementation can change that. Either the story needs that endpoint "
                        "(say so and test it once it exists) or the assertion does not belong."
                    )
                    continue
                expected = {int(m) for m in _STATUS_ASSERT.findall(block)}
                declared = {status_for[(method, p)] for p in matches if (method, p) in status_for}
                if expected and declared and not (expected & declared) and not (expected & {422, 404, 400, 405}):
                    issues.append(
                        f"{rel}::{name} expects status {sorted(expected)} from {method} {path}, "
                        f"which the route declares as {sorted(declared)}. Assert the status the "
                        "contract states."
                    )
            nonempty = _NONEMPTY.search(block)
            seed = _SEEDS.search(block)
            # A GET of a resource db/init.sql seeds is not empty: the test database
            # starts with those rows. A POST *after* the assertion seeds nothing.
            reads_seeded = any(_resource_table(call.group(3), seeded) for call in _CLIENT_CALL.finditer(block)
                               if call.group(1).upper() == "GET")
            if nonempty and not reads_seeded and (not seed or seed.start() > nonempty.start()):
                issues.append(
                    f"{rel}::{name} asserts a non-empty result but never creates the data it "
                    "expects — the test database starts empty, so this fails whatever the "
                    "implementation does. Create the row first (client.post, or db_session.add "
                    "then commit), or assert the shape of an empty result instead."
                )
            if _MARKUP.search(block):
                issues.append(
                    f"{rel}::{name} asserts HTML in an API response. The API returns data; the "
                    "markup lives in the screen, which the platform checks in a real browser. "
                    "Assert the data behind it."
                )
            hit = _LABELISH.search(block)
            if hit:
                issues.append(
                    f"{rel}::{name} asserts the label \"{hit.group(1)}\" inside a response field. "
                    "A button or link label belongs to the screen, not the payload."
                )
            for literal in re.findall(r"""==\s*['"]([^'"]{140,})['"]""", block):
                issues.append(
                    f"{rel}::{name} compares against {len(literal)} characters of text copied "
                    "verbatim. Content changes wording without changing meaning; assert that it "
                    "is present and names the key terms instead."
                )
    return list(dict.fromkeys(issues))


