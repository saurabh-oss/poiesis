_TABLE = re.compile(r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z_]\w*)\s*\([\s\S]*?\)\s*;", re.I)
def _elsewhere(root: Path, skip: str, proposed: dict[str, str]) -> str:
    """Everything in the backend and tests except one file, including proposed edits."""
    texts: list[str] = []
    for base in ("backend", "tests"):
        for p in (root / base).rglob("*.py"):
            rel = p.relative_to(root).as_posix()
            if rel != skip and rel not in proposed:
                texts.append(p.read_text(encoding="utf-8", errors="replace"))
    texts += [body for rel, body in proposed.items() if rel != skip]
    return "\n".join(texts)


REQUIREMENTS = "backend/requirements.txt"
_REQ_NAME = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")


def _req_name(line: str) -> str:
    m = _REQ_NAME.match(line)
    return m.group(1).lower().replace("_", "-") if m else ""


def merge_requirements(baseline: str, proposed: str) -> tuple[str, list[str]]:
    """The scaffold's pinned requirements plus whatever the story added.

    A story once replaced `psycopg[binary]==3.2.3` with `psycopg2-binary`, a
    different driver the SQLAlchemy URL does not use. Every test passed — the
    suite runs on SQLite — and the deployed API answered 500 to everything.
    Baseline lines are kept exactly; the story's additions follow.
    """
    base_lines = [l.rstrip() for l in baseline.splitlines() if l.strip() and not l.lstrip().startswith("#")]
    base_names = {_req_name(l) for l in base_lines}
    prop_lines = [l.rstrip() for l in proposed.splitlines() if l.strip() and not l.lstrip().startswith("#")]
    prop_names = {_req_name(l) for l in prop_lines}
    extra = [l for l in prop_lines if _req_name(l) not in base_names]
    restored = sorted(n for n in base_names if n not in prop_names)
    return "\n".join(base_lines + extra) + "\n", restored


def _baseline_requirements() -> str:
    from ..config import scaffold_root
