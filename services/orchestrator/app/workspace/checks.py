_COMMENTS = re.compile(r"//[^\n]*|/\*[\s\S]*?\*/")
_PLACEHOLDER = re.compile(r"\b(placeholder|todo|fixme|stub|not implemented|coming soon)\b", re.I)
_JSX = re.compile(r"return\s*\(\s*<|<>|</>|<[A-Z][A-Za-z0-9]*[\s/>]")
_API_CALL = re.compile(
    r"""\bapi\(\s*(?:(['"])(GET|POST|PUT|PATCH|DELETE)\1\s*,\s*)?(['"`])([^'"`]*)\3""", re.I
)
_BANNED: list[tuple[re.Pattern[str], str]] = [
    (re.compile(r"(?<![\w$])(?<!ui\.)(alert|confirm|prompt)\s*\("),
     "calls {0}() — the browser's dialog, not an interface. Use ui.confirm(), ui.formModal() or ui.toast()"),
    (re.compile(r"\bfetch\s*\("),
     "calls fetch() directly — use the api() render() receives: it adds /api, sends JSON and reports failures"),
    (re.compile(r"""getElementById\(\s*['"]app['"]\s*\)|querySelector\(\s*['"]#app['"]\s*\)|document\.body"""),
     "reaches outside its own root — build the screen only inside the `root` element render() is given"),
    (re.compile(r"""window\.onload|DOMContentLoaded|addEventListener\(\s*['"]load['"]"""),
     "wires its own page startup — the shell calls render(); a screen must not"),
    (re.compile(r"""\bimport\s[^;\n]*from\s*['"](?!\.)"""),
     "imports a package — there is no bundler; use only relative imports of your own files"),
]


def _defines(code: str, name: str) -> bool:
    """True when the screen declares its own function or variable called `name`."""
    return bool(re.search(rf"\bfunction\s*\*?\s*{name}\s*\(|\b(?:const|let|var)\s+{name}\s*=", code))


def _is_bare(path: str) -> bool:
    """A route at the root of /api: "/api/" itself, or "/api/{param}...".

    The second kind is the dangerous one. Mounted at /api, `@router.get("/{item_id}")`
    matches /api/anything, so it swallows every other story's GET and answers 422
    "item_id should be an integer" in their place.
    """
    rest = path[len("/api"):].strip("/") if path.startswith("/api") else path.strip("/")
    return rest == "" or rest.startswith("{")


def _route_pattern(route: str) -> re.Pattern[str]:
    # Trailing slashes are ignored on both sides: FastAPI redirects between them.
    escaped = re.escape(route.rstrip("/") or "/")
    escaped = re.sub(r"\\\{[^}]*\\\}", r"[^/]+", escaped)
    return re.compile(f"^{escaped}$")


def _normalise(path: str) -> str:
    path = path.split("?")[0].strip()
    # `/audit-entries${params}`: an expression glued to the end of a segment is a suffix
    # built elsewhere (a query string), not part of the path. Read as "/audit-entriesx" it
    # sent a correct audit screen round three repairs in the enterprise DupeGuard run.
    path = re.sub(r"(?<=[^/])(?:\$\{[^}]*\})+$", "", path)
    path = re.sub(r"\$\{[^}]*\}", "x", path)
    if not path.startswith("/"):
        path = "/" + path
    if not re.match(r"^/api(/|$)", path):
        path = "/api" + path
    return path.rstrip("/") or "/api"


# A screen that needs an id and gives up without one: `const id = params[0]; if (!id) { ...; return; }`
# before any api() call. The navigation opens every screen without parameters.
_PARAM_ID = re.compile(r"\bparams\s*(?:\[\s*0\s*\]|\?\.\[\s*0\s*\])|\bparams\s*\)|\[\s*\w+\s*\]\s*=\s*params")
_GUARD_OPEN = re.compile(r"if\s*\(([^{};]*)\)\s*\{")


def _is_id_guard(cond: str) -> bool:
    """`!id`, `!params || params.length === 0`, `params.length < 1`, `!ticketId`…"""
    c = cond.replace(" ", "")
    negative = "!" in c.replace("!=", "") or re.search(r"length(===?|<)(0|1)", c)
    about_id = re.search(r"params|id\b|Id\b|_id", cond)
    return bool(negative and about_id)


def _gives_up_without_id(code: str) -> tuple[int, str] | None:
    """The first `if (!x) { … return … }` block that runs before any api() call.

    Brace-aware, because the block usually builds an empty state with h() calls
    whose props are objects — a regex that forbids nested braces never matched.
    """
    for m in _GUARD_OPEN.finditer(code):
        if "api(" in code[:m.start()]:
            return None  # data was loaded first; a later guard is a real branch
        if not _is_id_guard(m.group(1)):
            continue
        depth, i, n = 1, m.end(), len(code)
        while i < n and depth:
            ch = code[i]
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
            i += 1
        block = code[m.end():i - 1]
        if re.search(r"\breturn\b", block) and "api(" not in block:
            return m.start(), code[m.start():m.end()]
    return None


_QUERY_KEY = re.compile(r"[?&]([A-Za-z_][A-Za-z0-9_]*)=")
_GENERIC_RESERVED = {"q", "sort", "limit", "offset", "page", "_"}


def _generic_filter_issue(run_id: str, rel: str, raw: str, called: str, routes: list[dict]) -> str:
    """A query filter on the generic data API that names a column the table lacks.

    The API answers 422 to it; before that it ignored the filter, and a "leavers"
    screen listed every employee.
    """
    if "?" not in raw:
        return ""
    serving = [r for r in routes if r["method"] == "GET" and _route_pattern(r["path"]).match(called)]
    if not serving or any(r.get("generic") is None for r in serving):
        return ""  # a story router serves it and reads its own parameters
    table = next((r["generic"] for r in serving if r.get("generic")), "")
    if not table:
        return ""
    from .interface import model_tables
    columns = set(model_tables(run_id).get(table, []))
    if not columns:
        return ""
    unknown = sorted({k for k in _QUERY_KEY.findall(raw) if k not in columns and k not in _GENERIC_RESERVED})
    if not unknown:
        return ""
    return (f"{rel}: filters {called} on {', '.join(unknown)}, which `{table}` does not have — the API answers "
            f"422. Its columns: {', '.join(sorted(columns))}. Filter on one of those (or fetch the list and "
            "filter in the screen).")


def _idless_issue(rel: str, code: str) -> str:
    """Why a screen would show nothing when opened from the navigation, or ''."""
    if not _PARAM_ID.search(code):
        return ""
    hit = _gives_up_without_id(code)
    if not hit:
        return ""
    return (f"{rel}: gives up when opened without an id (`{hit[1][:60].strip()}…`), and the navigation "
            "opens every screen without one — so a visitor sees only that message. When `params` is empty, "
            "fetch the list (`await api(\"/tickets\")`) and show it as a `ui.table` whose `onRow` navigates to "
            "this screen with the row's id; show the detail once an id is present.")


_RENDER_ARGS = re.compile(r"\brender\s*\(\s*\w+\s*,\s*\{([^}]*)\}")
_RENDER_GIVES = ("api", "h", "navigate", "params", "actions", "ui", "enterprise")


def _missing_render_args(rel: str, code: str) -> str:
    """A name the shell hands render() that the screen uses but did not take.

    `const incidentId = params[0]` with `render(root, { api, h, ui })` is a
    ReferenceError the moment the screen opens; it was found in the browser
    after deploy, a whole round late.
    """
    m = _RENDER_ARGS.search(code)
    if not m:
        return ""
    taken = {a.split(":")[0].strip() for a in m.group(1).split(",") if a.strip()}
    body = code[m.end():]
    missing = []
    for name in _RENDER_GIVES:
        if name in taken:
            continue
        if re.search(rf"(?<![\w.$]){name}\b(?!\s*[:=])", body) and not re.search(rf"\b(?:const|let|var)\s+{name}\b", body):
            missing.append(name)
    if not missing:
        return ""
    return (f"{rel}: uses {', '.join(f'`{n}`' for n in missing)} but render() does not receive it — "
            "a ReferenceError the moment the screen opens. Take everything from the shell: "
            "`async render(root, { api, h, navigate, params, actions, ui })` (and `enterprise` in an "
            "enterprise application).")


_RENDER = re.compile(r"\brender\s*\(")
_NESTED_FN = re.compile(r"(?:=>\s*|\bfunction\b\s*[\w$]*\s*\([^()]*\)\s*)\{")
_H_ELEMENT = re.compile(r"""\bh\(\s*(['"])(table|input|select|textarea)\1\s*,\s*\{([^{}]*)\}""")
_API_OPTIONS = re.compile(r"""\bapi\(\s*(['"`])([^'"`]*)\1\s*,\s*\{([^{}]*)\}""")
_CLASS_ATTR = re.compile(r"""\bclass\s*:\s*(['"`])([^'"`]*)\1""")
_OPTION_KEYS = {"method", "body", "headers"}
_COLLECTION = re.compile(r"""['"](?:tbody|table)['"]|empty-state""")


def _braced_body(code: str, open_at: int) -> tuple[str, int]:
    """The text inside the brace at or after `open_at`, and the index of its match."""
    start = code.find("{", open_at)
    if start < 0:
        return "", len(code)
    depth = 0
    for i in range(start, len(code)):
        if code[i] == "{":
            depth += 1
        elif code[i] == "}":
            depth -= 1
            if depth == 0:
                return code[start + 1:i], i
    return code[start + 1:], len(code)


def _matching_paren(code: str, open_at: int) -> int:
    """The index just past the `)` closing the `(` at `open_at - 1`."""
    depth = 0
    for i in range(open_at - 1, len(code)):
        if code[i] == "(":
            depth += 1
        elif code[i] == ")":
            depth -= 1
            if depth == 0:
                return i + 1
    return len(code)


def _render_body(code: str) -> str:
    """render()'s own body - skipping its parameter list, which is itself braced."""
    hit = _RENDER.search(code)
    if not hit:
        return ""
    return _braced_body(code, _matching_paren(code, hit.end()))[0]


def _outside_nested_functions(body: str) -> str:
    """`body` with every nested function body cut out, leaving render's own statements."""
    out: list[str] = []
    i = 0
    while i < len(body):
        hit = _NESTED_FN.search(body, i)
        if not hit:
            out.append(body[i:])
            break
        out.append(body[i:hit.start()])
        i = _braced_body(body, hit.end() - 1)[1] + 1
    return "".join(out)


def _screen_shell_issues(rel: str, code: str) -> list[str]:
    """Ways a screen misuses the shell that neither a test nor the browser check catches.

    Every one of these came out of a real run: the page rendered, nothing threw,
    the browser check called the screen working, and it showed the user nothing.
    """
    issues: list[str] = []

    body = _render_body(code)
    if body and _COLLECTION.search(body) and "await" not in _outside_nested_functions(body):
        issues.append(
            f"{rel}: render() never loads anything - it only calls the API from an event handler, so "
            "the screen opens empty and stays empty until someone clicks. Load the data in render() "
            'itself (`const rows = await api("/things")`), draw it, and have the handler reload it.'
        )

    for call in _API_OPTIONS.finditer(code):
        keys = set()
        for field in call.group(3).split(","):
            name = field.split(":")[0].strip()
            if re.fullmatch(r"[A-Za-z_$][\w$]*", name):
                keys.add(name)
        if keys and not (keys & _OPTION_KEYS):
            named = ", ".join(sorted(keys))
            issues.append(
                f'{rel}: api("{call.group(2)}", {{{named}}}) silently drops {named} - the second '
                "argument is the request itself (method, body, headers), not query parameters. Put "
                "them in the path: api(`/things?search=${encodeURIComponent(term)}`)."
            )

    for tag in _H_ELEMENT.finditer(code):
        classes = _CLASS_ATTR.search(tag.group(3))
        if not classes:
            continue
        names = set(classes.group(2).split())
        element = tag.group(2)
        if element == "table" and "table-wrap" in names:
            issues.append(
                f'{rel}: puts class "table-wrap" on the <table>. It is the scrolling frame that goes '
                'around one: h("div", {class: "table-wrap"}, h("table", {}, ...)).'
            )
        if element != "table" and "field" in names:
            issues.append(
                f'{rel}: puts class "field" on the <{element}>. It is the label-and-control wrapper '
                f'that goes around one: h("div", {{class: "field"}}, h("label", {{}}, "Name"), '
                f'h("{element}", {{}})).'
            )

    return issues


def static_issues(
    run_id: str, story_id: str | None, require_screen: bool, own_files: set[str] | None = None,
) -> list[str]:
    """Problems in the frontend and the route table.

    `own_files` are the files this story wrote. Router problems (a bare "/", a
    duplicate route) are reported only when this story's own file is involved:
    another story's leftover router is not something this story may edit, so
    failing it for one could never converge.
    """
    root = workspace_path(run_id)
    issues: list[str] = []
    routes = declared_routes(run_id)
    # A root catch-all ("/api/{id}") is not a real match for a screen's call: it
    # would pass /api/anything here and then answer 422 in the running app.
    patterns = [(r["method"], _route_pattern(r["path"])) for r in routes
                if not (_is_bare(r["path"]) and r["path"].rstrip("/") != "/api")]
    served = ", ".join(sorted({f"{r['method']} {r['path']}" for r in routes})) or "none"

    for path in story_screens(run_id):
        rel = path.relative_to(root).as_posix()
        text = path.read_text(encoding="utf-8", errors="replace")
        owners = stories_in(text)
        if story_id and owners and story_id not in owners:
            # Another story's screen: its own build checks it, and this story's
            # Developer is told not to edit it, so failing here could never converge.
            continue
        code = _COMMENTS.sub(" ", text)

        if "export default" not in code:
            issues.append(f"{rel}: has no `export default {{ title, story, render }}` — the shell cannot load it")
        if not stories_in(text):
            issues.append(f'{rel}: declares no story — add `story: "S1"` (the id of the story it delivers)')
        if _JSX.search(code):
            issues.append(f"{rel}: contains JSX — this is plain browser JavaScript; build elements with h()")
        for comment in _COMMENTS.findall(text):
            hit = _PLACEHOLDER.search(comment)
            if hit:
                issues.append(f"{rel}: a comment says '{hit.group(0)}' — a placeholder is not an implementation; "
                              "build the behaviour the acceptance criteria describe")
                break
        for pattern, message in _BANNED:
            hit = pattern.search(code)
            if hit and hit.groups() and _defines(code, hit.group(1)):
                # The screen's own `async function confirm(id)` (a review queue's
                # Confirm button) is not the browser's dialog. Flagging it once
                # made a correct story red after three repairs nobody could satisfy.
                hit = None
            if hit:
                issues.append(f"{rel}: " + message.format(hit.group(1) if hit.groups() else ""))
        issues += _screen_shell_issues(rel, code)
        idless = _idless_issue(rel, code)
        if idless:
            issues.append(idless)
        unreceived = _missing_render_args(rel, code)
        if unreceived:
            issues.append(unreceived)
        for call in _API_CALL.finditer(code):
            method = (call.group(2) or "").upper()
            called = _normalise(call.group(4))
            bad_filter = _generic_filter_issue(run_id, rel, call.group(4), called, routes)
            if bad_filter:
                issues.append(bad_filter)
            ok = any(p.match(called) and (not method or m == method) for m, p in patterns)
            if not ok:
                issues.append(f"{rel}: calls {method + ' ' if method else ''}{called}, which the API does not "
                              f"serve. Served routes: {served}")

    bare = sorted({r["file"] for r in routes
                   if r["file"].startswith("backend/app/routers/") and _is_bare(r["path"])})
    for rel in bare:
        if own_files is not None and rel not in own_files:
            continue
        issues.append(
            f"{rel}: declares routes at the root ('/' or '/{{id}}'), so they are served at /api/, "
            "where they collide with, or swallow, every other story's routes. Declare the "
            "resource on each route, e.g. "
            "@router.get(\"/llm-overviews\"), and call that same path from the screen."
        )

    seen: dict[tuple[str, str], str] = {}
    for r in routes:
        if r.get("generic") is not None:
            continue  # a story router that redeclares a generic path replaces it, by design
        key = (r["method"], r["path"])
        if key in seen and (own_files is None or seen[key] in own_files or r["file"] in own_files):
            issues.append(f"{r['method']} {r['path']} is declared twice ({seen[key]} and {r['file']}) — "
                          "keep one: return the redundant file with empty content (\"\") and the "
                          "platform deletes it, or remove the route from it")
        seen[key] = r["file"]

    if require_screen and story_id:
        if not any(story_id in stories_in(p.read_text(encoding="utf-8", errors="replace"))
                   for p in story_screens(run_id)):
            issues.append(
                f"{story_id} has no screen. Add frontend/screens/<resource>.js whose default export includes "
                f'`story: "{story_id}"` (or add {story_id} to the `story` field of the existing screen it extends). '
                "A story a user cannot reach in the browser is not implemented."
            )

    for path in router_files(run_id):
        if path.name in (EXAMPLE_ROUTER, GENERIC_ROUTER):
            continue  # the worked example and the platform's data API are not a story's content
        rel = path.relative_to(root).as_posix()
        if own_files is not None and rel not in own_files:
            continue
        src = path.read_text(encoding="utf-8", errors="replace")
        if re.search(r"@router\.", src) and not re.search(r"^\s*router\s*=\s*APIRouter\s*\(", src, re.M):
            issues.append(f"{rel}: uses `@router.get(...)` but never creates the router — `NameError: name "
                          "'router' is not defined` at import, which takes the whole API down. Add "
                          "`from fastapi import APIRouter` and `router = APIRouter()` above the endpoints.")
        issues += _seeding_issues(run_id, path, rel)

    return list(dict.fromkeys(issues))  # one line per problem, however many calls repeat it


_TABLE_NAME = re.compile(r"__tablename__\s*=\s*[\"']([^\"']+)[\"']")
_INSERT_INTO = re.compile(r"INSERT\s+INTO\s+([A-Za-z_]\w*)", re.I)
_DB_QUERY = re.compile(r"\.query\(\s*([A-Za-z_]\w*)")
_TEST_SEED = re.compile(r"db_session\.add\(\s*([A-Za-z_]\w*)")


def _model_tables(run_id: str) -> dict[str, str]:
    """Class name -> table name, read from backend/app/models.py."""
    path = workspace_path(run_id).joinpath(*PACKAGE_DIR, "models.py")
    if not path.is_file():
        return {}
    try:
        tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError:
        return {}
    out: dict[str, str] = {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        for stmt in node.body:
            if (isinstance(stmt, ast.Assign) and len(stmt.targets) == 1
                    and isinstance(stmt.targets[0], ast.Name) and stmt.targets[0].id == "__tablename__"
                    and isinstance(stmt.value, ast.Constant) and isinstance(stmt.value.value, str)):
                out[node.name] = stmt.value.value
    return out


def _model_columns(run_id: str) -> dict[str, tuple[str, set[str]]]:
    """table name -> (class name, {column attribute names}), from models.py.

    Assumes the attribute name is the column name, true of every model this
    scaffold has produced (`name: Mapped[str] = mapped_column(...)`); a
    `relationship()` isn't a column and is excluded, since it names a class,
    not a table.
    """
    path = workspace_path(run_id).joinpath(*PACKAGE_DIR, "models.py")
    if not path.is_file():
        return {}
    try:
        tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError:
        return {}
    out: dict[str, tuple[str, set[str]]] = {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        table = None
        columns: set[str] = set()
        for stmt in node.body:
            if not (isinstance(stmt, (ast.Assign, ast.AnnAssign))):
                continue
            target = stmt.targets[0] if isinstance(stmt, ast.Assign) else stmt.target
            if not isinstance(target, ast.Name):
                continue
            if target.id == "__tablename__":
                if isinstance(stmt.value, ast.Constant) and isinstance(stmt.value.value, str):
                    table = stmt.value.value
                continue
            is_relationship = (isinstance(stmt.value, ast.Call) and isinstance(stmt.value.func, ast.Name)
                               and stmt.value.func.id == "relationship")
            if not is_relationship:
                columns.add(target.id)
        if table:
            out[table] = (node.name, columns)
    return out


_CREATE_TABLE = re.compile(
    r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z_]\w*)\s*\((.*?)\)\s*;", re.I | re.S,
)
_SQL_CONSTRAINT_KEYWORDS = {"PRIMARY", "FOREIGN", "UNIQUE", "CONSTRAINT", "CHECK"}


def _split_top_level(body: str) -> list[str]:
    """Split a CREATE TABLE's column list on commas outside of `TYPE(...)` parens."""
    parts, current, depth = [], [], 0
    for ch in body:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(ch)
    parts.append("".join(current))
    return parts


def _sql_columns(run_id: str) -> dict[str, set[str]]:
    """table name (lowercase) -> {column names}, from every CREATE TABLE in db/init.sql."""
    init = workspace_path(run_id) / "db" / "init.sql"
    if not init.is_file():
        return {}
    text = strip_sql_comments(init.read_text(encoding="utf-8", errors="replace"))
    out: dict[str, set[str]] = {}
    for m in _CREATE_TABLE.finditer(text):
        table, columns = m.group(1).lower(), set()
        for part in _split_top_level(m.group(2)):
            first = part.strip().strip('"').split()
            if not first or first[0].upper() in _SQL_CONSTRAINT_KEYWORDS:
                continue
            columns.add(first[0].strip('"').lower())
        out[table] = columns
    return out


def schema_drift_issues(run_id: str) -> list[str]:
    """A model column db/init.sql's matching table does not have.

    The two files are meant to move together — the Developer is told to add a
    model to models.py "and" its CREATE TABLE to init.sql — but nothing enforces
    it, and pytest cannot: its test database is built straight from the models
    via `Base.metadata.create_all`, which can never disagree with them. Real
    Postgres runs on db/init.sql alone, so a forgotten column passes every test
    and fails only in the deployed app, as `column ... does not exist`.
    """
    sql_tables = _sql_columns(run_id)
    issues = []
    for table, (cls, columns) in _model_columns(run_id).items():
        sql_cols = sql_tables.get(table.lower())
        if sql_cols is None:
            continue  # a missing table entirely is a louder, differently-shaped failure
        missing = sorted(columns - sql_cols)
        if missing:
            issues.append(
                f"backend/app/models.py: `{cls}` declares column(s) {', '.join(missing)} that "
                f"db/init.sql's `{table}` table does not have. Add {', '.join(missing)} to its "
                f"`CREATE TABLE {table}` statement — this cannot be caught by the tests, only by "
                "the real deployment, because the test database is built from the model directly."
            )
    return issues


def _seeded_tables(run_id: str) -> set[str]:
    """Tables with a starting row in db/init.sql, or seeded by a story's own test fixture."""
    seeded: set[str] = set()
    init = workspace_path(run_id) / "db" / "init.sql"
    if init.is_file():
        seeded |= {m.group(1).lower() for m in _INSERT_INTO.finditer(
            init.read_text(encoding="utf-8", errors="replace"))}
    return seeded


def _seeding_issues(run_id: str, path: Path, rel: str) -> list[str]:
    """A GET endpoint reading a table nothing ever inserts a row into.

    A story that must show content on a fresh deployment — before any user has
    created anything — fails at exactly the moment that matters if that content
    lives in a database table with no seed data: unit tests miss this because a
    Tester routinely seeds the row itself with the `db_session` fixture inside
    the test, which proves nothing about the real, empty, deployed database.
    A GET endpoint that only forwards a bare `.query(Model)...` call, backed by
    a table with no `INSERT INTO` anywhere in db/init.sql, is flagged here
    directly against the failing test, which reads far more as an instruction
    than a paragraph in the system prompt does.
    """
    text = path.read_text(encoding="utf-8", errors="replace")
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return []
    tables = _model_tables(run_id)
    seeded = _seeded_tables(run_id)
    issues: list[str] = []
    for node in tree.body:
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        is_get = any(isinstance(d, ast.Call) and isinstance(d.func, ast.Attribute) and d.func.attr == "get"
                     for d in node.decorator_list)
        if not is_get:
            continue
        src = ast.get_source_segment(text, node) or ""
        if "return [" in src or "return {" in src or "return (" in src:
            continue  # returns a literal itself; not the empty-table pattern
        match = _DB_QUERY.search(src)
        if not match:
            continue
        model = match.group(1)
        table = tables.get(model)
        if table and table.lower() not in seeded:
            issues.append(
                f"{rel}: its GET endpoint returns `{model}` rows from the database, but nothing "
                f"seeds the `{table}` table — no `INSERT INTO {table}` in db/init.sql, and no other "
                "code populates it. On a fresh deployment, before any user has created anything, "
                "this endpoint returns an empty list and the screen has nothing to show, however "
                "the tests seeded their own copy of the database and passed. If the story's content "
                "is fixed rather than user-entered, return it as a literal from the endpoint instead "
                f"of querying the database; if it is real starting data, add `INSERT INTO {table}` "
                "statements to db/init.sql so a fresh deployment is never empty."
            )
    return issues


